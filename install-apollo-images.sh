#!/usr/bin/env bash
#
# install-apollo-images.sh - Apollo becomes forge's PRIMARY IMAGE SERVER
# (30 October 2026), and keeps coding.
#
# Apollo (RX 9070 XT 16 GB, 32 GB RAM) gets the same sd-server as Mercury:
# stable-diffusion.cpp on Vulkan with Qwen-Image-2.1, on :7860 - by running
# install-mercury-imagegen.sh's phases here (vulkan verify build models
# server firewall; NOT its `base` phase, which is Mercury's OS setup). It
# renders FULL steps (no Lightning) - the quality job Vulcan used to do -
# while Mercury keeps the fast Lightning renders.
#
# Sharing the GPU with Apollo's coder (TielCoder, llama-server router):
# sd-server keeps its weights in RAM (--offload-to-cpu) and takes VRAM only
# while it renders; forge codes on Apollo only once its renders are done and
# unloads every coder model before a render. RAM is the tight part: the
# coder's experts in RAM (N_CPU_MOE) plus sd-server's ~11 GB resident -
# check `free -g` during the first run.
#
# Put install-mercury-imagegen.sh next to this script. Run as your normal
# user on Apollo:   ./install-apollo-images.sh
# Then on Gemini:   python3 ~/forge/apply-roles.py   (adds Apollo to
#                   [[images.servers]]) and `forge check`.

set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
say()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
ok()   { printf '\033[1;32m ok\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m !!\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31mERR\033[0m %s\n' "$*" >&2; exit 1; }

[ "$(id -u)" -ne 0 ] || die "Run as your normal user, not root."
case "$(hostname | tr '[:upper:]' '[:lower:]')" in
    apollo*) ;;
    *) die "This is $(hostname), not Apollo." ;;
esac
[ -f "$HERE/install-mercury-imagegen.sh" ] || die "install-mercury-imagegen.sh is not next to this script."

say "Apollo's coder stays as it is:"
systemctl --user is-active llama-server >/dev/null 2>&1 && ok "llama-server (coder) active" \
    || warn "llama-server is not active - the coder is down; images still install"
free -g | awk '/^Mem:/ {printf "    RAM %s GB total, %s GB available now\n", $2, $7}'

bash "$HERE/install-mercury-imagegen.sh" vulkan verify build models server firewall

unit="$HOME/.config/systemd/user/sd-server.service"
if [ -f "$unit" ]; then
    sed -i 's/^Description=Mercury sd-server.*/Description=Apollo sd-server - Qwen-Image-2.1 on RX 9070 XT (Vulkan)/' "$unit"
    sed -i 's/^# Auto-generated by install-mercury-imagegen.sh/# Auto-generated by install-mercury-imagegen.sh (via install-apollo-images.sh)/' \
        "$HOME/run_sd.sh" 2>/dev/null || true
    systemctl --user daemon-reload
    systemctl --user enable --now sd-server
    ok "sd-server enabled on Apollo"
fi

say "Waiting for sd-server on :7860"
for _ in $(seq 1 60); do
    curl -fsS http://127.0.0.1:7860/sdapi/v1/loras >/dev/null 2>&1 && { ok "sd-server answers"; break; }
    sleep 5
done
cat <<'EOF'

    Next:
      - on Gemini:  python3 ~/forge/apply-roles.py && ~/forge/forge.py check
      - first renders: watch  free -g  and  journalctl --user -u sd-server -f
        here; if RAM runs short, raise the coder's N_CPU_MOE less (fewer
        experts in RAM) or lower sd-server's resident weights.
      - Apollo is clamped to x1.5 hires (max_hr_scale) like Mercury: a 2x 4K
        pass crashed the Vulkan driver on Mercury. Test x2 on Apollo with
        ~/sd-lightning-test.py-style renders before raising it.
EOF
