#!/usr/bin/env bash
#
# fo4-probe2.sh - Fallout 4, second round. Run on Gemini after fo4-probe.sh:
#     bash fo4-probe2.sh [path to the Fallout 4 install]
#
# Round 1: Mutagen READS Fallout4.esm fine, but writing an override failed:
# "Could not determine plugin listings path ... LocalAppData environment
# variable is not set". And the Creation Kit's Papyrus compiler RUNS under
# Mono; it only rejected how the probe named the script, and the base script
# sources were not found (they are in Base.zip, deeper than the probe looked).
#
# This round:
#   1. Finds your load order (plugins.txt) in Fallout 4's Proton prefix, or
#      makes one from the masters in Data/, and gives Mutagen a LocalAppData
#      folder holding it (as plugins.txt and Plugins.txt: Linux is
#      case-sensitive).
#   2. Writes ForgeProbe.esp two ways - new records only, and new records plus
#      an override of a Fallout4.esm record - and reads each back. No network.
#   3. Extracts Base.zip (to ~/fo4-probe, the install is not changed) and
#      compiles two scripts with the Papyrus compiler under Mono: one plain,
#      one in a namespace folder (ForgeProbe:Quests:...). No network.
# Report: ~/fo4-probe/report2.txt
#
set -uo pipefail
FO4="${1:-$HOME/.steam/debian-installation/steamapps/common/Fallout 4}"
FO4="$(cd "$FO4" 2>/dev/null && pwd)" || { echo "Fallout 4 install not found"; exit 1; }
OUT="$HOME/fo4-probe"
SDK="${SDK_IMAGE:-mcr.microsoft.com/dotnet/sdk:10.0}"
MONO="${MONO_IMAGE:-mono:6.12}"
[ -f "$OUT/app/ForgeProbe.csproj" ] || { echo "Run fo4-probe.sh first."; exit 1; }
R="$OUT/report2.txt"; : > "$R"
log() { printf '%s\n' "$*" | tee -a "$R"; }
sec() { log ""; log "=== $* ==="; }
log "date: $(date -Is)  install: $FO4"

sec "load order"
LAD="$OUT/localappdata"
rm -rf "$LAD"; mkdir -p "$LAD/Fallout4"
STEAMROOT="$(cd "$FO4/../../.." && pwd)"           # .../steamapps/common/Fallout 4 -> library root
REAL="$(find "$STEAMROOT/steamapps/compatdata/377160" -ipath '*AppData/Local/Fallout4/plugins.txt' 2>/dev/null | head -1)"
if [ -n "$REAL" ]; then
    log "found: $REAL"
    cp "$REAL" "$LAD/Fallout4/plugins.txt"
else
    log "no plugins.txt in the Proton prefix (compatdata/377160) - generating one from Data/"
    {
        echo "# generated by fo4-probe2.sh"
        for m in DLCRobot.esm DLCworkshop01.esm DLCCoast.esm DLCworkshop02.esm DLCworkshop03.esm DLCNukaWorld.esm; do
            [ -f "$FO4/Data/$m" ] && echo "*$m"
        done
        ls "$FO4/Data" | grep -i '\.esl$' | sed 's/^/*/'
    } > "$LAD/Fallout4/plugins.txt"
fi
cp "$LAD/Fallout4/plugins.txt" "$LAD/Fallout4/Plugins.txt"
log "plugins.txt ($(wc -l < "$LAD/Fallout4/plugins.txt") lines):"
sed 's/^/  /' "$LAD/Fallout4/plugins.txt" | head -40 | tee -a "$R" >/dev/null
log "Fallout4.ccc (Creation Club load order): $(tr -d '\r' < "$FO4/Fallout4.ccc" 2>/dev/null | tr '\n' ' ' | cut -c1-300)"

sec "Mutagen: write two ways"
cat > "$OUT/app/Program.cs" <<'EOF'
using System;
using System.IO;
using System.Linq;
using Mutagen.Bethesda;
using Mutagen.Bethesda.Fallout4;
using Mutagen.Bethesda.Plugins;
using Mutagen.Bethesda.Plugins.Records;

static class Probe
{
	static int Main(string[] args)
	{
		var data = args[0];
		var outDir = args[1];
		var mode = args[2];                        // "new" or "override"
		Directory.CreateDirectory(outDir);
		Console.WriteLine($"mode {mode}; LocalAppData={Environment.GetEnvironmentVariable("LocalAppData")}");
		using var esm = Fallout4Mod.CreateFromBinaryOverlay(Path.Combine(data, "Fallout4.esm"), Fallout4Release.Fallout4);
		var sample = esm.MiscItems.First(m => !string.IsNullOrEmpty(m.EditorID));
		var outPath = Path.Combine(outDir, "ForgeProbe.esp");
		try
		{
			var mod = new Fallout4Mod(ModKey.FromFileName("ForgeProbe.esp"), Fallout4Release.Fallout4);
			var misc = mod.MiscItems.AddNew();
			misc.EditorID = "ForgeProbeTag";
			misc.Name = "Forge probe tag";
			misc.Value = 7;
			var quest = mod.Quests.AddNew();
			quest.EditorID = "ForgeProbeQuest";
			quest.Name = "Forge probe";
			if (mode == "override")
			{
				var over = mod.MiscItems.GetOrAddAsOverride(sample);
				over.Value = 99;
			}
			((IModGetter)mod).WriteToBinary(outPath);
			Console.WriteLine($"WRITE_OK {new FileInfo(outPath).Length} bytes");
		}
		catch (Exception e) { Console.WriteLine($"WRITE_FAILED {e.GetType().Name}: {e.Message}\n{e.StackTrace?.Split('\n').FirstOrDefault()}"); return 1; }
		try
		{
			using var back = Fallout4Mod.CreateFromBinaryOverlay(outPath, Fallout4Release.Fallout4);
			var tag = back.MiscItems.First(m => m.EditorID == "ForgeProbeTag");
			Console.WriteLine($"read back: misc {back.MiscItems.Count}, quests {back.Quests.Count}, masters [{string.Join(", ", back.ModHeader.MasterReferences.Select(m => m.Master.FileName))}], tag {tag.FormKey} value {tag.Value} name '{tag.Name?.String}'");
			if (mode == "override")
			{
				var ov = back.MiscItems.First(m => m.FormKey == sample.FormKey);
				Console.WriteLine($"override of {sample.EditorID}: value {ov.Value} (expected 99)");
			}
			Console.WriteLine("READBACK_OK");
		}
		catch (Exception e) { Console.WriteLine($"READBACK_FAILED {e.GetType().Name}: {e.Message}"); return 1; }
		return 0;
	}
}
EOF
for mode in new override; do
    rm -rf "$OUT/out-$mode"; mkdir -p "$OUT/out-$mode"
    out="$(timeout 900 docker run --rm --network none --user "$(id -u):$(id -g)" \
        -v "$FO4":/fo4:ro -v "$OUT/app":/work/app -v "$OUT/out-$mode":/work/out \
        -v "$OUT/nuget":/nuget -v "$OUT/home":/home/probe -v "$LAD":/lad:ro \
        -e HOME=/home/probe -e DOTNET_CLI_HOME=/home/probe -e NUGET_PACKAGES=/nuget \
        -e DOTNET_CLI_TELEMETRY_OPTOUT=1 -e DOTNET_NOLOGO=1 -e LocalAppData=/lad \
        -w /work/app "$SDK" bash -c \
        "dotnet build --no-restore -c Release -o /work/app/bin 2>&1 | grep -E ' error |Build succeeded' | head -10; dotnet /work/app/bin/ForgeProbe.dll /fo4/Data /work/out $mode" 2>&1)"
    log "--- $mode (exit $?):"
    printf '%s\n' "$out" | tail -15 | tee -a "$R" >/dev/null
done
log "ForgeProbe.esp files: $(ls -la "$OUT"/out-*/ForgeProbe.esp 2>/dev/null | awk '{print $5" bytes "$NF}' | tr '\n' ' ')"

sec "Papyrus: base sources"
log "zips under Data/Scripts: $(find "$FO4/Data/Scripts" -iname '*.zip' 2>/dev/null | sed "s#$FO4/##" | tr '\n' ' ')"
BZ="$(find "$FO4/Data/Scripts" -iname 'Base.zip' 2>/dev/null | head -1)"
PB="$OUT/papyrus/Base"
if [ -n "$BZ" ]; then
    rm -rf "$PB"; mkdir -p "$PB"
    python3 -c "import zipfile,sys; zipfile.ZipFile(sys.argv[1]).extractall(sys.argv[2])" "$BZ" "$PB"
    log "extracted $BZ -> $PB"
else
    log "no Base.zip found; using Data/Scripts/Source/Base as is"
    PB="$FO4/Data/Scripts/Source/Base"
fi
log "  .psc files: $(find "$PB" -iname '*.psc' | wc -l)"
FLG="$(find "$PB" "$FO4/Data/Scripts/Source" -iname 'Institute_Papyrus_Flags.flg' 2>/dev/null | head -1)"
log "  flags file: ${FLG:-NOT FOUND}"
QUEST="$(find "$PB" -iname 'Quest.psc' | head -1)"
log "  Quest.psc at: ${QUEST#"$PB"/}"
# The compiler resolves a script against the import folders: Base's root is
# the folder that holds Quest.psc (namespaces are subfolders of it).
PBROOT="$(dirname "${QUEST:-$PB/x}")"

sec "Papyrus: compile under Mono"
PC="$(find "$FO4" -maxdepth 3 -iname 'PapyrusCompiler.exe' | head -1)"
W="$OUT/papyrus"
rm -rf "$W/src" "$W/pex"; mkdir -p "$W/src/ForgeProbe/Quests" "$W/pex"
cat > "$W/src/ForgeProbeScript.psc" <<'EOF'
ScriptName ForgeProbeScript extends Quest

Int Property Counter = 0 Auto

Event OnInit()
    Counter += 1
    Debug.Trace("forge probe: OnInit " + Counter)
EndEvent
EOF
cat > "$W/src/ForgeProbe/Quests/TrackerScript.psc" <<'EOF'
ScriptName ForgeProbe:Quests:TrackerScript extends Quest

GlobalVariable Property ForgeProbeCount Auto

Function Bump(Int amount)
    ForgeProbeCount.SetValue(ForgeProbeCount.GetValue() + amount)
EndFunction
EOF
docker pull -q "$MONO" >/dev/null 2>&1 || true
compile() {  # file relative to src
    timeout 600 docker run --rm --network none --user "$(id -u):$(id -g)" -e HOME=/tmp \
        -v "$FO4":/fo4:ro -v "$PBROOT":/base:ro -v "$(dirname "${FLG:-$PBROOT/x}")":/flags:ro \
        -v "$W":/work -w /work/src "$MONO" \
        mono "/fo4/${PC#"$FO4"/}" "$1" "-f=$(basename "${FLG:-Institute_Papyrus_Flags.flg}")" \
        "-i=/work/src;/base;/flags" -o=/work/pex 2>&1 | grep -v -E "runtime version supported|Using default runtime"
}
for f in ForgeProbeScript.psc ForgeProbe/Quests/TrackerScript.psc; do
    log "--- $f"
    compile "$f" | tail -12 | tee -a "$R" >/dev/null
done
log "compiled: $(cd "$W/pex" && find . -iname '*.pex' -printf '%p (%s bytes) ' 2>/dev/null)"

echo
echo "Report: $R"
